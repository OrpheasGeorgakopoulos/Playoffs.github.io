-- Estia Shootout leaderboard — run once in Supabase → SQL Editor → New query → Run.
-- Anyone can read the board and add a score; nobody can edit or delete from the website.
-- To remove a fake score: Supabase → Table Editor → scores → select the row → Delete.

create table if not exists public.scores (
  id          bigint generated by default as identity primary key,
  name        text        not null check (char_length(name) between 2 and 16),
  score       int         not null check (score between 1 and 400),
  team        text        check (team in ('pat', 'gly')),
  made        int         not null check (made between 1 and 60),
  shots       int         not null check (shots between 1 and 80),
  created_at  timestamptz not null default now(),
  -- a basket is worth at most 8 (3-pointer ×2 on fire, +2 money ball)
  constraint scores_plausible check (made <= shots and score <= made * 8)
);

create index if not exists scores_week_idx on public.scores (created_at desc, score desc);

alter table public.scores enable row level security;

drop policy if exists "scores are public" on public.scores;
create policy "scores are public" on public.scores for select using (true);

drop policy if exists "anyone can add a score" on public.scores;
create policy "anyone can add a score" on public.scores for insert with check (true);

grant select, insert on public.scores to anon, authenticated;

-- Anti-spam: one game takes 30+ seconds, so the same name can't post faster than that,
-- and the whole board accepts at most 30 new scores per minute.
create or replace function public.scores_guard() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  new.created_at := now();
  new.name := btrim(regexp_replace(new.name, '\s+', ' ', 'g'));
  if exists (select 1 from public.scores
             where lower(name) = lower(new.name) and created_at > now() - interval '30 seconds') then
    raise exception 'too fast';
  end if;
  if (select count(*) from public.scores where created_at > now() - interval '1 minute') >= 30 then
    raise exception 'too fast';
  end if;
  return new;
end $$;

drop trigger if exists scores_guard on public.scores;
create trigger scores_guard before insert on public.scores
  for each row execute function public.scores_guard();
